def native_errors(exc):
    codes = []
    for arg in getattr(exc, 'args', ())[1:]:
        if not isinstance(arg, str):
            continue
        for match in re.finditer(r'\((\d{1,6})\)(?=\s*(?:\(SQL\w+\)|;|$))', arg):
            code = int(match.group(1))
            if code in ERRORS and code not in codes:
                codes.append(code)
    return ' '.join(f'SQL Server {code}: {ERRORS[code]}' for code in codes)
